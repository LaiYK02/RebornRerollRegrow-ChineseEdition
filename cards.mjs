export function monsterProfile(id, biome) {
  const { atk, def, hp } = cards[id];
  const bonus = id.startsWith("e")
    ? ({ rainforest: 1, volcano: 2 }[biome] ?? 0)
    : 0;
  return { atk: atk + bonus, def: def + bonus, hp: hp + bonus };
}
